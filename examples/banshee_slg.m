function banshee_slg()
%BANSHEE_SLG Quantify the rung-1 grounding finding: SLG faults on Banshee's
%   islanded 13.8 kV zones under three grounding designs.
%
%   The grounding gate established structurally that every islanded MV zone
%   has no zero-sequence source. This example puts numbers on it for ISL_F1
%   (feeder 1 islanded on the 4 MVA diesel), where a machine island has a
%   classical sequence Thevenin: Z1 ~= Xd'' (0.15 pu on 4 MVA) plus the tie
%   line, on the 20 MVA system base.
%
%   Three designs are compared, because the first "obvious" remediation
%   teaches the wrong lesson if presented alone:
%     1. As released (ungrounded)     -- sqrt(3) overvoltage, zero fault current
%     2. Low-resistance zig-zag (Rn)  -- detectable current, damage limited, but
%                                        the temporary overvoltage is NOT fixed
%     3. Effective grounding (X0-dom) -- overvoltage held, paid for with the
%                                        highest fault current
%   That is the standard grounding design triangle: overvoltage vs fault
%   current vs arc damage. Pick two.
addpath(fullfile(fileparts(mfilename("fullpath")), ".."));
RULE = string(repmat('=', 1, 78));

BASE = mgtwin.Base(s_base_mva=20.0, v_base_kv=13.8, f_base_hz=60.0);
V_LN = 13.8e3 / sqrt(3);
% Diesel 4 MVA, Xd'' = 0.15 pu own base -> 20 MVA base, plus 2000 ft of
% 13.8 kV feeder (positive-sequence approximation from the case data).
Z1 = 1i * 0.15 * (20.0 / 4.0) + complex(0.0128, 0.0214);

    function show(title, consequence, varargin)
        fprintf("\n%s\n", title);
        res = mgtwin.slgFault(Z1, varargin{:});
        disp(res.render(i_base_a=BASE.i_base_a, v_base_ln=V_LN));
        disp(consequence);
    end

disp(RULE);
disp("SLG fault on the islanded 13.8 kV zone (ISL_F1, diesel island)");
disp(RULE);
fprintf("Z1 = Z2 = %.3f + j%.3f pu on 20 MVA / 13.8 kV\n", real(Z1), imag(Z1));

show("1. As released -- no zero-sequence source in the zone:", ...
    "   consequence   : phase-ground insulation and arresters sized near" + newline + ...
    "                   1.0 pu see 1.73 pu for as long as the fault" + newline + ...
    "                   persists -- and it persists, because there is no" + newline + ...
    "                   neutral current for a ground relay to measure.", ...
    "z0_pu", []);

rn_ohm = 12.0;
z0_lrg = 3.0 * mgtwin.zigzagZ0Pu(rn_ohm, 13.8, 20.0) + 1i * 0.10;
show(sprintf("2. Low-resistance grounding -- zig-zag with %.0f-ohm neutral resistor:", rn_ohm), ...
    "   consequence   : the fault is now DETECTABLE (a 51G element has" + newline + ...
    "                   hundreds of amperes to work with) and arc damage is" + newline + ...
    "                   limited -- but note the overvoltage: a resistive Z0" + newline + ...
    "                   against a reactive Z1 rotates the unfaulted phasors" + newline + ...
    "                   and the worst phase slightly EXCEEDS sqrt(3). LRG" + newline + ...
    "                   buys detection and damage limitation, not" + newline + ...
    "                   overvoltage relief; insulation stays full line-line" + newline + ...
    "                   rated. This is why 'add a grounding bank' is not" + newline + ...
    "                   the end of the design conversation.", ...
    "z0_pu", z0_lrg);

z0_eff = 0.05 + 1i * 1.6;   % X0/X1 ~= 2.0, R0/X1 << 1: effectively grounded
show("3. Effective grounding -- low-impedance bank, X0/X1 ~= 2:", ...
    "   consequence   : overvoltage held to ~1.2 pu (COG well under 0.8;" + newline + ...
    "                   reduced-rating arresters are admissible), paid for" + newline + ...
    "                   with the largest ground-fault current of the three" + newline + ...
    "                   -- which the 4 MVA diesel must survive and the" + newline + ...
    "                   switchgear must interrupt.", ...
    "z0_pu", z0_eff);

fprintf("\n%s\n", RULE);
disp("The design triangle in one table: overvoltage vs fault current vs" + newline + ...
    "damage -- pick two. The released benchmark sits at the worst corner" + newline + ...
    "for an islanded system: full overvoltage AND an undetectable fault." + newline + newline + ...
    "ISL_F2 (PV-only island): conclusion 1 is identical -- sqrt(3) is a" + newline + ...
    "property of the missing zero-sequence path, not of the source. But" + newline + ...
    "quantifying designs 2 and 3 there requires the converter's current-" + newline + ...
    "limited fault model, which the release does not contain. That is the" + newline + ...
    "same gap gateModelHonesty flags, now with an engineering" + newline + ...
    "consequence attached.");
end
