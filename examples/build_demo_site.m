function site = build_demo_site(remediated)
%BUILD_DEMO_SITE The demonstration microgrid used by examples/demo.m and
%   the unit tests.
%
%   As handed over (remediated=false) it contains two defects that survive
%   human review: the grounding reference sits outside the microgrid, and
%   relay pickup was carried over from the grid-connected study. Both are
%   caught structurally by the gates. remediated=true is the same site
%   after the fixes.
arguments
    remediated (1,1) logical = false
end
import mgtwin.*
base = Base(s_base_mva=10.0, v_base_kv=11.0, f_base_hz=50.0);

buses = [ ...
    Bus(id="BUS_UTIL", v_nom_kv=33.0, is_poi=true); ...
    Bus(id="BUS_MV", v_nom_kv=11.0); ...
    Bus(id="BUS_LOAD", v_nom_kv=11.0)];

transformers = Transformer(id="TX1", hv_bus="BUS_UTIL", lv_bus="BUS_MV", s_rated_mva=15.0, ...
    hv_kv=33.0, lv_kv=11.0, x_pu=0.08, r_pu=0.006, ...
    hv_config=WindingConfig.WYE_GROUNDED, ...
    lv_config=WindingConfig.DELTA);   % delta on the microgrid side: no zero-sequence path inside

branches = Branch(id="FDR1", from_bus="BUS_MV", to_bus="BUS_LOAD", r_pu=0.012, x_pu=0.028, ...
    s_base_mva=10.0, v_base_kv=11.0, rating_mva=12.0);

switches = [ ...
    Switch(id="SW_PCC", from_bus="BUS_UTIL", to_bus="BUS_MV", is_pcc=true); ...
    Switch(id="SW_MV", from_bus="BUS_MV", to_bus="BUS_LOAD")];

if remediated, steady = 1.10; else, steady = []; end
if remediated, fw1 = "4.2.1"; fw2 = "2.8.0"; else, fw1 = ""; fw2 = ""; end
converters = [ ...
    Converter(id="BESS_1", bus="BUS_MV", s_rated_mva=5.0, control=ConverterControl.GFM_DROOP, ...
        params=ConverterParams(p_f_droop_pu=0.05, q_v_droop_pu=0.05, h_sec=2.0, tp_sec=0.20, ...
            i_limit_transient_pu=1.20, i_limit_steady_pu=steady, ride_through_identified=remediated), ...
        vendor="(vendor)", firmware=fw1, energy_mwh=10.0); ...
    Converter(id="PV_1", bus="BUS_LOAD", s_rated_mva=3.0, control=ConverterControl.GFL, ...
        params=ConverterParams(tp_sec=0.05, i_limit_transient_pu=1.20, i_limit_steady_pu=steady, ...
            ride_through_identified=remediated), ...
        firmware=fw2)];

machines = SynchronousGen(id="DG_1", bus="BUS_MV", s_rated_mva=2.0, h_sec=1.2, ...
    xd_subtransient_pu=0.18, droop_pu=0.04, neutral_grounded=remediated);

loads = [ ...
    Load(id="LD_CRIT", bus="BUS_LOAD", p_mw=2.5, q_mvar=0.8, critical=true); ...
    Load(id="LD_GEN", bus="BUS_LOAD", p_mw=3.5, q_mvar=1.1)];

grounding = GroundingSource(id="G_UTIL", bus="BUS_UTIL", kind=GroundingKind.SOLID, ...
    available_when_islanded=false, notes="Utility substation neutral, upstream of the PCC.");
if remediated
    grounding(end+1, 1) = GroundingSource(id="G_ZIGZAG", bus="BUS_MV", kind=GroundingKind.LOW_RESISTANCE, ...
        z0_ohm=12.0, available_when_islanded=true, ...
        notes="Zig-zag grounding transformer added inside the microgrid.");
end

% Pickup originally set from grid-connected fault duty, where the utility
% contributes several thousand amperes. Remediation adds an islanded
% settings group.
if remediated, pickup = 300.0; note = "islanded settings group"; else, pickup = 600.0; note = "grid-connected settings"; end
relays = OvercurrentRelay(id="R_MV", switch_id="SW_MV", ct_ratio=600.0, pickup_a=pickup, time_dial=0.30, notes=note);

islands = [ ...
    IslandConfig(id="ISL_0", description="Grid-connected, normal", grid_connected=true, ...
        energized_source_ids=["BESS_1", "PV_1", "DG_1"]); ...
    IslandConfig(id="ISL_1", description="Islanded, all local sources available", open_switches="SW_PCC", ...
        grid_connected=false, energized_source_ids=["BESS_1", "PV_1", "DG_1"]); ...
    IslandConfig(id="ISL_2", description="Islanded, genset on maintenance outage (converters only)", ...
        open_switches="SW_PCC", grid_connected=false, energized_source_ids=["BESS_1", "PV_1"])];

site = Site(id="DEMO_MG", name="Demonstration microgrid", base=base, buses=buses, branches=branches, ...
    transformers=transformers, switches=switches, relays=relays, converters=converters, ...
    machines=machines, loads=loads, grounding=grounding, islands=islands);
end
