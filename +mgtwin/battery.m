function scs = battery()
%BATTERY The adversarial scenario battery for identification evals.
%
%   Each truth plant either IS the library form (nominal) or contains a
%   mechanism the library form deliberately lacks. The identifier is scored
%   on whether it REFUSES when the form is wrong, not on how close its
%   (necessarily biased) estimates land.
base = {"rp_pu", 0.05, "tp_sec", 0.20, "h_sec", 2.0};
P = @(varargin) mgtwin.PlantParams(base{:}, varargin{:});
S = @(varargin) mgtwin.Scenario(varargin{:});
scs = [ ...
    S(name="nominal", params=P(), mismatch=false, ...
      note="library form exact; baseline for true confidence"), ...
    S(name="nominal_high_noise", params=P(), mismatch=false, ...
      note="same plant, 5x measurement noise (false-alarm probe)"), ...
    S(name="quantized", params=P(), mismatch=false, quantize_pu=1e-4, ...
      note="nominal plant, 6 mHz measurement quantization"), ...
    S(name="fast_unmodeled", params=P(extra_lag_sec=0.005), mismatch=false, ...
      note="5 ms unmodeled lag: bias ~2.5%, genuinely minor; counts as over-refusal if refused"), ...
    S(name="ramp_limit", params=P(ramp_limit_pu_s=0.30), mismatch=true, ...
      note="BESS ramp limiter vs 0.4 pu step"), ...
    S(name="deadband", params=P(deadband_hz=0.20), mismatch=true, ...
      note="governor deadband +/-0.2 Hz"), ...
    S(name="saturation", params=P(p_max_pu=0.50), mismatch=true, step=[0.20, 0.60], ...
      note="output clamp at 0.5 pu; step demands 0.6"), ...
    S(name="extra_lag", params=P(extra_lag_sec=0.15), mismatch=true, ...
      note="150 ms actuator lag: 3rd-order truth, 2nd-order fit"), ...
    S(name="knee_droop", params=P(knee=[0.15, 0.02]), mismatch=true, ...
      note="droop steepens to 2% beyond +/-0.15 Hz (FFR-style)")];
end
