function r = plausibleRanges()
%PLAUSIBLERANGES [low, high] physically plausible ranges for distribution-class
%   microgrids. Deliberately wide -- these catch order-of-magnitude errors,
%   not tuning errors.
r = struct( ...
    "v_base_kv",  [0.2, 138.0], ...
    "s_base_mva", [0.01, 500.0], ...
    "x_over_r",   [0.1, 50.0], ...
    "z_pu",       [1e-5, 5.0], ...
    "droop_pu",   [0.005, 0.20], ...   % 0.5%-20% P-f droop
    "h_sec",      [0.0, 20.0], ...     % virtual/real inertia constant
    "tp_sec",     [1e-3, 5.0], ...     % power measurement filter
    "i_limit_pu", [0.8, 3.0], ...      % converter current limit on own rating
    "tx_x_pu",    [0.02, 0.25]);       % power transformer reactance on its own rating
end
